//! The `CREATE` of an object, rebuilt from the catalog as `pg_dump` and DBeaver write it.
use super::{RELATION, database_of, query, text, unknown};
use crate::connection::PgConnection;
use nexo_driver_sdk::{Result, protocol::Ddl};
use tokio_postgres::{Client, types::ToSql};

type Params<'a> = [&'a (dyn ToSql + Sync); 2];

/// `CREATE TABLE` with its columns, constraints, partitioning, indexes, comments, owner and
/// grants.
async fn table(client: &Client, version: i32, params: &Params<'_>) -> Result<String> {
    let header = format!(
        "SELECT format('%I.%I', n.nspname, c.relname), c.relkind::text, c.relpersistence::text, \
        quote_ident(pg_get_userbyid(c.relowner)), quote_literal(obj_description(c.oid, 'pg_class')), {partition} \
        FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE c.oid = {RELATION}",
        partition = if version >= 100000 {
            "CASE WHEN c.relkind = 'p' THEN pg_get_partkeydef(c.oid) END, \
             CASE WHEN c.relispartition THEN (SELECT format('%s %s', i.inhparent::regclass, pg_get_expr(c.relpartbound, c.oid)) \
             FROM pg_inherits i WHERE i.inhrelid = c.oid) END"
        } else {
            "NULL::text, NULL::text"
        }
    );
    let rows = query(client, &header, params).await?;
    let row = rows.first().ok_or_else(unknown)?;
    let (name, kind, persistence) = (text(row, 0), text(row, 1), text(row, 2));
    let (owner, comment, partition_key, partition_of) =
        (text(row, 3), text(row, 4), text(row, 5), text(row, 6));
    let unlogged = if persistence == "u" { "UNLOGGED " } else { "" };
    let mut sql = String::new();
    if let Some((parent, bound)) = partition_of
        .split_once(' ')
        .filter(|_| !partition_of.is_empty())
    {
        sql.push_str(&format!(
            "CREATE {unlogged}TABLE {name} PARTITION OF {parent}\n    {bound};\n"
        ));
    } else {
        let identity = if version >= 100000 {
            "a.attidentity::text"
        } else {
            "''"
        };
        let generated = if version >= 120000 {
            "a.attgenerated::text"
        } else {
            "''"
        };
        let columns = format!(
            "SELECT format('%I', a.attname), format_type(a.atttypid, a.atttypmod), a.attnotnull, \
            pg_get_expr(d.adbin, d.adrelid), {identity}, {generated}, \
            CASE WHEN a.attcollation <> t.typcollation THEN format(' COLLATE %I', co.collname) ELSE '' END \
            FROM pg_attribute a JOIN pg_type t ON t.oid = a.atttypid \
            LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum \
            LEFT JOIN pg_collation co ON co.oid = a.attcollation \
            WHERE a.attrelid = {RELATION} AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum"
        );
        let mut lines: Vec<String> = query(client, &columns, params)
            .await?
            .iter()
            .map(|row| {
                let mut line = format!("    {} {}{}", text(row, 0), text(row, 1), text(row, 6));
                let (default, identity, generated) = (text(row, 3), text(row, 4), text(row, 5));
                match (identity.as_str(), generated.as_str()) {
                    ("a", _) => line.push_str(" GENERATED ALWAYS AS IDENTITY"),
                    ("d", _) => line.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
                    (_, "s") => line.push_str(&format!(" GENERATED ALWAYS AS ({default}) STORED")),
                    _ if !default.is_empty() => line.push_str(&format!(" DEFAULT {default}")),
                    _ => {}
                }
                if row.get::<_, bool>(2) {
                    line.push_str(" NOT NULL");
                }
                line
            })
            .collect();
        let constraints = format!(
            "SELECT format('%I', conname), pg_get_constraintdef(oid) FROM pg_constraint \
            WHERE conrelid = {RELATION} ORDER BY contype <> 'p', contype <> 'u', contype = 'f', conname"
        );
        for row in query(client, &constraints, params).await? {
            lines.push(format!(
                "    CONSTRAINT {} {}",
                text(&row, 0),
                text(&row, 1)
            ));
        }
        let table_kind = if kind == "f" {
            "FOREIGN TABLE"
        } else {
            "TABLE"
        };
        sql.push_str(&format!(
            "CREATE {unlogged}{table_kind} {name} (\n{}\n)",
            lines.join(",\n")
        ));
        if !partition_key.is_empty() {
            sql.push_str(&format!(" PARTITION BY {partition_key}"));
        }
        sql.push_str(";\n");
    }
    // Indexes that no constraint creates.
    let indexes = format!(
        "SELECT pg_get_indexdef(x.indexrelid) FROM pg_index x WHERE x.indrelid = {RELATION} \
        AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = x.indexrelid AND c.conrelid = x.indrelid) \
        ORDER BY 1"
    );
    for row in query(client, &indexes, params).await? {
        sql.push_str(&format!("\n{};", text(&row, 0)));
    }
    if !comment.is_empty() {
        sql.push_str(&format!("\n\nCOMMENT ON TABLE {name} IS {comment};"));
    }
    let comments = format!(
        "SELECT format('%I', a.attname), quote_literal(col_description(a.attrelid, a.attnum)) \
        FROM pg_attribute a WHERE a.attrelid = {RELATION} AND a.attnum > 0 AND NOT a.attisdropped \
        AND col_description(a.attrelid, a.attnum) IS NOT NULL ORDER BY a.attnum"
    );
    for row in query(client, &comments, params).await? {
        sql.push_str(&format!(
            "\nCOMMENT ON COLUMN {name}.{} IS {};",
            text(&row, 0),
            text(&row, 1)
        ));
    }
    sql.push_str(&format!("\n\nALTER TABLE {name} OWNER TO {owner};"));
    let grants = format!(
        "SELECT a.privilege_type, CASE WHEN a.grantee = 0 THEN 'PUBLIC' \
        ELSE quote_ident(pg_get_userbyid(a.grantee)) END FROM pg_class c, aclexplode(c.relacl) a \
        WHERE c.oid = {RELATION} AND a.grantee <> c.relowner ORDER BY 2, 1"
    );
    for row in query(client, &grants, params).await? {
        sql.push_str(&format!(
            "\nGRANT {} ON {name} TO {};",
            text(&row, 0),
            text(&row, 1)
        ));
    }
    Ok(sql)
}

async fn single(client: &Client, sql: &str, params: &[&(dyn ToSql + Sync)]) -> Result<String> {
    let rows = query(client, sql, params).await?;
    rows.first()
        .map(|row| text(row, 0))
        .filter(|text| !text.is_empty())
        .ok_or_else(unknown)
}

pub(crate) async fn ddl(connection: &PgConnection, path: &[String]) -> Result<Ddl> {
    let path = super::resolved(path);
    let (database, client) = database_of(connection, &path).await?;
    let segments: Vec<&str> = path.iter().map(String::as_str).collect();
    let version = connection.version;
    let sql = match segments.as_slice() {
        [_] => format!("CREATE DATABASE {};", single(&client, "SELECT quote_ident($1::text)", &[&database]).await?),
        [_, "schemas", schema] => single(&client, "SELECT format('CREATE SCHEMA %I AUTHORIZATION %I;', nspname, \
            pg_get_userbyid(nspowner)) FROM pg_namespace WHERE nspname = $1", &[schema]).await?,
        [_, "schemas", schema, "tables" | "foreign-tables", name] => table(&client, version, &[schema, name]).await?,
        [_, "schemas", schema, folder @ ("views" | "materialized-views"), name] => {
            let create = if *folder == "views" { "CREATE OR REPLACE VIEW" } else { "CREATE MATERIALIZED VIEW" };
            let sql = format!("SELECT format('{create} %I.%I AS\n%s', $1::text, $2::text, pg_get_viewdef({RELATION}, true))");
            single(&client, &sql, &[schema, name]).await?
        }
        [_, "schemas", _, "functions" | "procedures", oid] => {
            let oid: u32 = oid.parse().map_err(|_| unknown())?;
            format!("{};", single(&client, "SELECT pg_get_functiondef($1)", &[&oid]).await?.trim_end())
        }
        [_, "schemas", schema, "sequences", name] if version >= 100000 => single(&client, "SELECT format(\
            'CREATE SEQUENCE %I.%I AS %s INCREMENT BY %s MINVALUE %s MAXVALUE %s START WITH %s CACHE %s%s;', \
            schemaname, sequencename, data_type, increment_by, min_value, max_value, start_value, cache_size, \
            CASE WHEN cycle THEN ' CYCLE' ELSE '' END) FROM pg_sequences WHERE schemaname = $1 AND sequencename = $2", &[schema, name]).await?,
        [_, "schemas", schema, "types", name] => single(&client, "SELECT CASE t.typtype \
            WHEN 'e' THEN format('CREATE TYPE %I.%I AS ENUM (%s);', n.nspname, t.typname, \
                (SELECT string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder) FROM pg_enum e WHERE e.enumtypid = t.oid)) \
            WHEN 'c' THEN format('CREATE TYPE %I.%I AS (%s);', n.nspname, t.typname, \
                (SELECT string_agg(format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod)), ', ' ORDER BY a.attnum) \
                 FROM pg_attribute a WHERE a.attrelid = t.typrelid AND a.attnum > 0 AND NOT a.attisdropped)) \
            WHEN 'd' THEN format('CREATE DOMAIN %I.%I AS %s%s%s;', n.nspname, t.typname, format_type(t.typbasetype, t.typtypmod), \
                CASE WHEN t.typnotnull THEN ' NOT NULL' ELSE '' END, \
                coalesce((SELECT string_agg(' ' || pg_get_constraintdef(c.oid), '') FROM pg_constraint c WHERE c.contypid = t.oid), '')) \
            WHEN 'r' THEN format('CREATE TYPE %I.%I AS RANGE (SUBTYPE = %s);', n.nspname, t.typname, \
                (SELECT format_type(r.rngsubtype, NULL) FROM pg_range r WHERE r.rngtypid = t.oid)) END \
            FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace WHERE n.nspname = $1 AND t.typname = $2", &[schema, name]).await?,
        [_, "schemas", schema, "indexes", name] => format!("{};", single(&client, "SELECT pg_get_indexdef(i.oid) FROM pg_class i \
            JOIN pg_namespace n ON n.oid = i.relnamespace WHERE n.nspname = $1 AND i.relname = $2", &[schema, name]).await?),
        [_, "extensions", name] => single(&client, "SELECT format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I VERSION %L;', \
            e.extname, n.nspname, e.extversion) FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace \
            WHERE e.extname = $1", &[name]).await?,
        [_, "roles", name] => single(&client, "SELECT format('CREATE ROLE %I WITH %s%s%s%s;', rolname, \
            CASE WHEN rolcanlogin THEN 'LOGIN' ELSE 'NOLOGIN' END, CASE WHEN rolsuper THEN ' SUPERUSER' ELSE '' END, \
            CASE WHEN rolcreatedb THEN ' CREATEDB' ELSE '' END, CASE WHEN rolcreaterole THEN ' CREATEROLE' ELSE '' END) \
            FROM pg_roles WHERE rolname = $1", &[name]).await?,
        [_, "schemas", schema, _, table, part, item] => {
            let sql = match *part {
                "constraints" | "foreign-keys" => format!("SELECT format('ALTER TABLE %I.%I ADD CONSTRAINT %I %s;', $1::text, $2::text, \
                    conname, pg_get_constraintdef(oid)) FROM pg_constraint WHERE conrelid = {RELATION} AND conname = $3"),
                "indexes" => format!("SELECT pg_get_indexdef(x.indexrelid) || ';' FROM pg_index x \
                    JOIN pg_class i ON i.oid = x.indexrelid WHERE x.indrelid = {RELATION} AND i.relname = $3"),
                "triggers" => format!("SELECT pg_get_triggerdef(oid, true) || ';' FROM pg_trigger \
                    WHERE tgrelid = {RELATION} AND tgname = $3"),
                "columns" => format!("SELECT format('ALTER TABLE %I.%I ADD COLUMN %I %s;', $1::text, $2::text, a.attname, \
                    format_type(a.atttypid, a.atttypmod)) FROM pg_attribute a WHERE a.attrelid = {RELATION} AND a.attname = $3"),
                _ => return Err(unknown()),
            };
            single(&client, &sql, &[schema, table, item]).await?
        }
        _ => return Err(unknown()),
    };
    Ok(Ddl { sql })
}
