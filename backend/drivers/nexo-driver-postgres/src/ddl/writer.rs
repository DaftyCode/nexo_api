//! The DDL of PostgreSQL for each change of a table (adapted in part from DBeaver, Apache-2.0:
//! plugins/org.jkiss.dbeaver.ext.postgresql/edit, `PostgreTableManager` and
//! `PostgreTableColumnManager`). Every change is made in place, and in a transaction.
use nexo_driver_sdk::ddl::{
    ColumnModel, Constraint, DdlWriter, ForeignKeyModel, IndexModel, KeyModel, Step, TableModel,
    index_part,
};

pub struct PgWriter;

fn literal(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

impl PgWriter {
    fn names(&self, names: &[String]) -> String {
        names
            .iter()
            .map(|name| self.quote(name))
            .collect::<Vec<_>>()
            .join(", ")
    }
    fn key(&self, kind: &str, key: &KeyModel) -> String {
        let name = if key.name.is_empty() {
            String::new()
        } else {
            format!("CONSTRAINT {} ", self.quote(&key.name))
        };
        format!("{name}{kind} ({})", self.names(&key.columns))
    }
    fn foreign(&self, key: &ForeignKeyModel) -> String {
        let name = if key.name.is_empty() {
            String::new()
        } else {
            format!("CONSTRAINT {} ", self.quote(&key.name))
        };
        let table = match &key.referenced_schema {
            Some(schema) => format!(
                "{}.{}",
                self.quote(schema),
                self.quote(&key.referenced_table)
            ),
            None => self.quote(&key.referenced_table),
        };
        let mut sql = format!(
            "{name}FOREIGN KEY ({}) REFERENCES {table} ({})",
            self.names(&key.columns),
            self.names(&key.referenced_columns)
        );
        for (event, action) in [("DELETE", &key.on_delete), ("UPDATE", &key.on_update)] {
            if !action.is_empty() && action != "NO ACTION" {
                sql.push_str(&format!(" ON {event} {action}"));
            }
        }
        sql
    }
    fn constraint(&self, constraint: &Constraint) -> String {
        match constraint {
            Constraint::PrimaryKey(key) => self.key("PRIMARY KEY", key),
            Constraint::Unique(key) => self.key("UNIQUE", key),
            Constraint::Check(check) if check.name.is_empty() => {
                format!("CHECK ({})", check.expression)
            }
            Constraint::Check(check) => format!(
                "CONSTRAINT {} CHECK ({})",
                self.quote(&check.name),
                check.expression
            ),
            Constraint::ForeignKey(key) => self.foreign(key),
        }
    }
    fn comment_on(&self, what: String, comment: Option<&str>) -> String {
        let comment = comment
            .filter(|text| !text.is_empty())
            .map_or("NULL".into(), literal);
        format!("COMMENT ON {what} IS {comment}")
    }
}

impl DdlWriter for PgWriter {
    fn table(&self, table: &TableModel) -> String {
        match &table.schema {
            Some(schema) => format!("{}.{}", self.quote(schema), self.quote(&table.name)),
            None => self.quote(&table.name),
        }
    }
    fn quote(&self, name: &str) -> String {
        format!("\"{}\"", name.replace('"', "\"\""))
    }
    fn column(&self, _: &TableModel, column: &ColumnModel) -> String {
        let mut sql = format!("{} {}", self.quote(&column.name), column.type_name);
        if column.identity {
            sql.push_str(" GENERATED BY DEFAULT AS IDENTITY");
        } else if let Some(default) = column.default.as_deref().filter(|text| !text.is_empty()) {
            sql.push_str(&format!(" DEFAULT {default}"));
        }
        if !column.nullable {
            sql.push_str(" NOT NULL");
        }
        sql
    }
    fn create(&self, table: &TableModel) -> Vec<String> {
        let mut parts: Vec<String> = table
            .columns
            .iter()
            .map(|c| self.column(table, c))
            .collect();
        let constraints = table
            .primary_key
            .iter()
            .map(|key| Constraint::PrimaryKey(key.clone()))
            .chain(table.uniques.iter().cloned().map(Constraint::Unique))
            .chain(table.checks.iter().cloned().map(Constraint::Check))
            .chain(
                table
                    .foreign_keys
                    .iter()
                    .cloned()
                    .map(Constraint::ForeignKey),
            );
        parts.extend(constraints.map(|constraint| self.constraint(&constraint)));
        let mut statements = vec![format!(
            "CREATE TABLE {} (\n  {}\n)",
            self.table(table),
            parts.join(",\n  ")
        )];
        if let Some(comment) = table.comment.as_deref().filter(|text| !text.is_empty()) {
            statements.push(self.comment_on(format!("TABLE {}", self.table(table)), Some(comment)));
        }
        for column in &table.columns {
            if let Some(comment) = column.comment.as_deref().filter(|text| !text.is_empty()) {
                let on = format!("COLUMN {}.{}", self.table(table), self.quote(&column.name));
                statements.push(self.comment_on(on, Some(comment)));
            }
        }
        statements
    }
    fn drop(&self, table: &TableModel, cascade: bool) -> Vec<String> {
        let cascade = if cascade { " CASCADE" } else { "" };
        vec![format!("DROP TABLE {}{cascade}", self.table(table))]
    }
    fn rename_table(&self, table: &TableModel, to: &str) -> Step {
        Step::one(format!(
            "ALTER TABLE {} RENAME TO {}",
            self.table(table),
            self.quote(to)
        ))
    }
    fn table_comment(&self, table: &TableModel, _: Option<&str>, after: Option<&str>) -> Step {
        Step::one(self.comment_on(format!("TABLE {}", self.table(table)), after))
    }
    fn add_column(&self, table: &TableModel, column: &ColumnModel) -> Step {
        let mut statements = vec![format!(
            "ALTER TABLE {} ADD COLUMN {}",
            self.table(table),
            self.column(table, column)
        )];
        if let Some(comment) = column.comment.as_deref().filter(|text| !text.is_empty()) {
            let on = format!("COLUMN {}.{}", self.table(table), self.quote(&column.name));
            statements.push(self.comment_on(on, Some(comment)));
        }
        Step::Run(statements)
    }
    fn drop_column(&self, table: &TableModel, column: &str) -> Step {
        Step::one(format!(
            "ALTER TABLE {} DROP COLUMN {}",
            self.table(table),
            self.quote(column)
        ))
    }
    fn rename_column(&self, table: &TableModel, from: &str, to: &str) -> Step {
        Step::one(format!(
            "ALTER TABLE {} RENAME COLUMN {} TO {}",
            self.table(table),
            self.quote(from),
            self.quote(to)
        ))
    }
    fn alter_column(&self, table: &TableModel, before: &ColumnModel, after: &ColumnModel) -> Step {
        let alter = format!(
            "ALTER TABLE {} ALTER COLUMN {}",
            self.table(table),
            self.quote(&after.name)
        );
        let mut statements = Vec::new();
        if !before.type_name.eq_ignore_ascii_case(&after.type_name) {
            statements.push(format!(
                "{alter} TYPE {} USING {}::{}",
                after.type_name,
                self.quote(&after.name),
                after.type_name
            ));
        }
        if before.identity && !after.identity {
            statements.push(format!("{alter} DROP IDENTITY"));
        }
        if before.default != after.default && !after.identity {
            match after.default.as_deref().filter(|text| !text.is_empty()) {
                Some(default) => statements.push(format!("{alter} SET DEFAULT {default}")),
                None => statements.push(format!("{alter} DROP DEFAULT")),
            }
        }
        if !before.identity && after.identity {
            statements.push(format!("{alter} ADD GENERATED BY DEFAULT AS IDENTITY"));
        }
        if before.nullable != after.nullable {
            let set = if after.nullable { "DROP" } else { "SET" };
            statements.push(format!("{alter} {set} NOT NULL"));
        }
        Step::Run(statements)
    }
    fn column_comment(&self, table: &TableModel, _: &ColumnModel, after: &ColumnModel) -> Step {
        let on = format!("COLUMN {}.{}", self.table(table), self.quote(&after.name));
        Step::one(self.comment_on(on, after.comment.as_deref()))
    }
    fn add_constraint(&self, table: &TableModel, constraint: &Constraint) -> Step {
        Step::one(format!(
            "ALTER TABLE {} ADD {}",
            self.table(table),
            self.constraint(constraint)
        ))
    }
    fn drop_constraint(&self, table: &TableModel, constraint: &Constraint) -> Step {
        Step::one(format!(
            "ALTER TABLE {} DROP CONSTRAINT {}",
            self.table(table),
            self.quote(constraint.name())
        ))
    }
    fn create_index(&self, table: &TableModel, index: &IndexModel) -> String {
        let unique = if index.unique { "UNIQUE " } else { "" };
        let method = if index.method.is_empty() {
            String::new()
        } else {
            format!(" USING {}", index.method)
        };
        let columns: Vec<String> = index
            .columns
            .iter()
            .map(|column| index_part(self, column))
            .collect();
        let mut sql = format!(
            "CREATE {unique}INDEX {} ON {}{method} ({})",
            self.quote(&index.name),
            self.table(table),
            columns.join(", ")
        );
        if !index.condition.is_empty() {
            sql.push_str(&format!(" WHERE {}", index.condition));
        }
        sql
    }
    fn drop_index(&self, table: &TableModel, index: &IndexModel) -> String {
        match &table.schema {
            Some(schema) => format!(
                "DROP INDEX {}.{}",
                self.quote(schema),
                self.quote(&index.name)
            ),
            None => format!("DROP INDEX {}", self.quote(&index.name)),
        }
    }
    fn transactional(&self) -> bool {
        true
    }
}
