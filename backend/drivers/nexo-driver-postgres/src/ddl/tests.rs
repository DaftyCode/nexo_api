//! The DDL PostgreSQL gets for each change: a table of cases through the plan.
use super::{check_expression, writer::PgWriter};
use nexo_driver_sdk::ddl::{
    ColumnModel, DdlPlanParams, ForeignKeyModel, IndexModel, KeyModel, TableModel, plan,
};

fn column(name: &str, type_name: &str, nullable: bool) -> ColumnModel {
    ColumnModel {
        name: name.into(),
        original: name.into(),
        type_name: type_name.into(),
        nullable,
        ..ColumnModel::default()
    }
}
fn orders() -> TableModel {
    TableModel {
        schema: Some("shop".into()),
        name: "orders".into(),
        original: "orders".into(),
        columns: vec![
            ColumnModel {
                identity: true,
                ..column("id", "integer", false)
            },
            column("customer", "integer", false),
            column("note", "varchar(20)", true),
        ],
        primary_key: Some(KeyModel {
            name: "orders_pkey".into(),
            columns: vec!["id".into()],
        }),
        foreign_keys: vec![ForeignKeyModel {
            name: "orders_customer".into(),
            columns: vec!["customer".into()],
            referenced_schema: Some("shop".into()),
            referenced_table: "customers".into(),
            referenced_columns: vec!["id".into()],
            on_delete: "CASCADE".into(),
            ..ForeignKeyModel::default()
        }],
        indexes: vec![IndexModel {
            name: "orders_note".into(),
            columns: vec!["note DESC".into()],
            condition: "note IS NOT NULL".into(),
            ..IndexModel::default()
        }],
        ..TableModel::default()
    }
}
fn params(original: Option<TableModel>, target: Option<TableModel>) -> DdlPlanParams {
    DdlPlanParams {
        connection: "c".into(),
        original,
        target,
        cascade: true,
    }
}

#[test]
fn creates_a_table_with_its_keys_and_indexes() {
    let mut table = orders();
    table.original.clear();
    table.columns[2].comment = Some("what the buyer's note says".into());
    let planned = plan(&PgWriter, &params(None, Some(table))).unwrap();
    assert_eq!(
        planned.statements,
        [
            "CREATE TABLE \"shop\".\"orders\" (\n  \"id\" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  \"customer\" integer NOT NULL,\n  \"note\" varchar(20),\n  CONSTRAINT \"orders_pkey\" PRIMARY KEY (\"id\"),\n  CONSTRAINT \"orders_customer\" FOREIGN KEY (\"customer\") REFERENCES \"shop\".\"customers\" (\"id\") ON DELETE CASCADE\n)",
            "COMMENT ON COLUMN \"shop\".\"orders\".\"note\" IS 'what the buyer''s note says'",
            "CREATE INDEX \"orders_note\" ON \"shop\".\"orders\" (\"note\" DESC) WHERE note IS NOT NULL",
        ]
    );
    assert!(planned.transactional);
    let dropped = plan(&PgWriter, &params(Some(orders()), None)).unwrap();
    assert_eq!(
        dropped.statements,
        ["DROP TABLE \"shop\".\"orders\" CASCADE"]
    );
}

#[test]
fn alters_a_column_and_adds_another() {
    let mut after = orders();
    after.columns[2].type_name = "text".into();
    after.columns[2].nullable = false;
    after.columns[2].default = Some("''".into());
    after.columns.push(ColumnModel {
        name: "total".into(),
        type_name: "numeric(10,2)".into(),
        nullable: true,
        default: Some("0".into()),
        ..ColumnModel::default()
    });
    after.checks.push(nexo_driver_sdk::ddl::CheckModel {
        name: "orders_total".into(),
        expression: "total >= 0".into(),
    });
    let planned = plan(&PgWriter, &params(Some(orders()), Some(after))).unwrap();
    assert_eq!(
        planned.statements,
        [
            "ALTER TABLE \"shop\".\"orders\" ALTER COLUMN \"note\" TYPE text USING \"note\"::text",
            "ALTER TABLE \"shop\".\"orders\" ALTER COLUMN \"note\" SET DEFAULT ''",
            "ALTER TABLE \"shop\".\"orders\" ALTER COLUMN \"note\" SET NOT NULL",
            "ALTER TABLE \"shop\".\"orders\" ADD COLUMN \"total\" numeric(10,2) DEFAULT 0",
            "ALTER TABLE \"shop\".\"orders\" ADD CONSTRAINT \"orders_total\" CHECK (total >= 0)",
        ]
    );
}

#[test]
fn reads_the_expression_of_a_check() {
    assert_eq!(check_expression("CHECK ((total > 0))"), "(total > 0)");
    assert_eq!(check_expression("CHECK (a IS NOT NULL)"), "a IS NOT NULL");
}
