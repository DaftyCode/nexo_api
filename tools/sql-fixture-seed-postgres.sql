-- The data of the PostgreSQL driver tests (tools/sql-fixture.sh): a schema with related
-- tables and every kind of object the tree shows, a table of 100 000 rows and a table with a
-- column of each type, with known values.
CREATE EXTENSION IF NOT EXISTS hstore;
CREATE SCHEMA shop;
CREATE TYPE shop.status AS ENUM ('new', 'paid', 'sent');
CREATE TYPE shop.address AS (street text, city text);
CREATE DOMAIN shop.positive AS numeric(12, 2) CHECK (VALUE >= 0);

CREATE TABLE shop.customers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    name text,
    created timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE shop.customers IS 'People who buy';
COMMENT ON COLUMN shop.customers.email IS 'Where receipts go';

CREATE TABLE shop.orders (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer integer NOT NULL REFERENCES shop.customers (id) ON DELETE CASCADE,
    status shop.status NOT NULL DEFAULT 'new',
    total shop.positive NOT NULL,
    CONSTRAINT orders_total_small CHECK (total < 1000000)
);
CREATE INDEX orders_status ON shop.orders (status) WHERE status <> 'sent';

CREATE VIEW shop.open_orders AS SELECT id, customer, total FROM shop.orders WHERE status <> 'sent';
CREATE MATERIALIZED VIEW shop.totals AS SELECT customer, sum(total) AS total FROM shop.orders GROUP BY customer;
CREATE SEQUENCE shop.invoice_numbers START 1000 INCREMENT 10;

CREATE FUNCTION shop.order_count(customer_id integer) RETURNS bigint LANGUAGE sql STABLE
    AS $$ SELECT count(*) FROM shop.orders WHERE customer = customer_id $$;
CREATE PROCEDURE shop.mark_sent(order_id bigint) LANGUAGE sql
    AS $$ UPDATE shop.orders SET status = 'sent' WHERE id = order_id $$;
CREATE FUNCTION shop.touch() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;
CREATE TRIGGER orders_touch BEFORE UPDATE ON shop.orders FOR EACH ROW EXECUTE FUNCTION shop.touch();

CREATE TABLE shop.events (id bigint, happened date NOT NULL) PARTITION BY RANGE (happened);
CREATE TABLE shop.events_2026 PARTITION OF shop.events FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');

